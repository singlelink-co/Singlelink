import mysql from 'mysql2/promise';

// Database connection configuration
// It's important to use environment variables for sensitive information
const dbConfig = {
  host: process.env.DB_HOST,
  port: Number(process.env.DB_PORT),
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_DATABASE,
};

// Function to get a database connection
// In a production app, you'd typically use a connection pool
export async function getDbConnection() { // Added export
  const connection = await mysql.createConnection(dbConfig);
  return connection;
}

// Function to find a user by email
export async function findUserByEmail(email: string) {
  const connection = await getDbConnection();
  try {
    const [rows] = await connection.execute(
      'SELECT id, name, email, password, role, subscription_plan FROM `users` WHERE `email` = ?',
      [email]
    );
    // mysql2/promise returns an array [rows, fields]
    // We expect rows to be an array of user objects
    if (Array.isArray(rows) && rows.length > 0) {
      return rows[0] as any; // Cast to 'any' for now, define a User type later if needed
    }
    return null;
  } catch (error) {
    console.error('Error finding user by email:', error);
    throw error; // Re-throw the error to be handled by the caller
  } finally {
    await connection.end();
  }
}

// Function to get all users for the admin panel
export async function getAllUsers() {
  const connection = await getDbConnection();
  try {
    const [rows] = await connection.execute(
      'SELECT id, name, email, role, subscription_plan, stripe_customer_id, stripe_subscription_status, created_at FROM `users` ORDER BY created_at DESC'
    );
    return rows as any[]; // Define a User type for admin panel later if needed
  } catch (error) {
    console.error('Error fetching all users:', error);
    throw error;
  } finally {
    await connection.end();
  }
}

// Function to get the ID of the first user found in the database
// This is a placeholder for a more robust user selection mechanism for public pages
export async function getFirstUserId(): Promise<string | null> {
  const connection = await getDbConnection();
  try {
    const [rows] = await connection.execute(
      'SELECT id FROM `users` LIMIT 1'
    );
    if (Array.isArray(rows) && rows.length > 0) {
      return (rows[0] as any).id;
    }
    return null;
  } catch (error) {
    console.error('Error fetching first user ID:', error);
    throw error;
  } finally {
    await connection.end();
  }
}

// Function to create a new user
export async function createUser(name: string | null, email: string, hashedPassword: string) {
  const connection = await getDbConnection();
  try {
    const [result] = await connection.execute(
      'INSERT INTO `users` (`id`, `name`, `email`, `password`, `emailVerified`) VALUES (UUID(), ?, ?, ?, NOW())', // Assuming id is UUID generated by DB or use a library
      [name, email, hashedPassword]
    );
    // mysql2/promise returns a ResultSetHeader for INSERT operations
    // We can check result.insertId if the ID is auto-incremented, or assume success if no error
    if ((result as any).affectedRows === 1) {
        // Fetch the created user to return it (excluding password)
        const [rows] = await connection.execute(
            'SELECT id, name, email, subscription_plan FROM `users` WHERE `email` = ?',
            [email]
        );
        if (Array.isArray(rows) && rows.length > 0) {
            return rows[0] as any;
        }
    }
    return null;
  } catch (error) {
    console.error('Error creating user:', error);
    // Check for duplicate email error (ER_DUP_ENTRY)
    if ((error as any).code === 'ER_DUP_ENTRY') {
      throw new Error('User with this email already exists.');
    }
    throw error; // Re-throw other errors
  } finally {
    await connection.end();
  }
}
